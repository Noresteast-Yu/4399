class MetroStation {
  final String id;
  final String name;
  final double x;
  final double y;
  final List<String> transferLines;
  final int order;

  const MetroStation({
    required this.id,
    required this.name,
    required this.x,
    required this.y,
    this.transferLines = const [],
    required this.order,
  });
}

class MetroLine {
